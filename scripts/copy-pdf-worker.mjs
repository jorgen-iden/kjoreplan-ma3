// Copies the pdf.js worker into public/ so it is served from our own origin (no CDN, no network
// request to third parties). Runs on every npm install.
//
// We use the legacy build: it polyfills the newest JavaScript features pdf.js uses (e.g.
// Map.getOrInsertComputed, Math.sumPrecise), which Safari on iPhone lacks. public/pdf.worker.mjs
// is a small wrapper that also adds `for await` over ReadableStream, then loads the worker.
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { installStreamIterator } from '../src/lib/parse/stream-iterator.mjs';

const require = createRequire(import.meta.url);
const src = require.resolve('pdfjs-dist/legacy/build/pdf.worker.min.mjs');
const out = new URL('../public/', import.meta.url);
mkdirSync(out, { recursive: true });
copyFileSync(src, new URL('pdf.worker.legacy.min.mjs', out));
// The import runs first, but the worker only reads streams later, when a file arrives.
writeFileSync(
  new URL('pdf.worker.mjs', out),
  `// Generated by scripts/copy-pdf-worker.mjs. Do not edit.\nimport './pdf.worker.legacy.min.mjs';\n(${installStreamIterator.toString()})();\n`,
);
